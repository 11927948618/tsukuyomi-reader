// Regenerates js/webapp/lexer-source.js (the only third-party code shipped for webapp packs).
//
//   cd <any scratch dir>; npm i es-module-lexer esbuild
//   node <repo>/scripts/build-webapp-vendor.mjs
//
// es-module-lexer (MIT, (c) Guy Bedford) minimal asm.js build is bundled as an IIFE exposing a global `ESL`
// and stored as a JS string so the sandbox launcher never needs a network fetch at start-up.
// Dev-only dependencies (esbuild, es-module-lexer) are NOT part of the production repo.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const requireFromCwd = createRequire(path.join(process.cwd(), "noop.js"));
const { build } = requireFromCwd("esbuild");
const lexerDir = path.join(process.cwd(), "node_modules", "es-module-lexer");
const lexerPkg = JSON.parse(fs.readFileSync(path.join(lexerDir, "package.json"), "utf8"));
const entry = path.join(lexerDir, "dist", "lexer.minimal.asm.js");

const result = await build({
  entryPoints: [entry], bundle: true, minify: true, format: "iife", globalName: "ESL", write: false, legalComments: "none", target: "es2018"
});
const code = result.outputFiles[0].text.trim();
const banner = `// GENERATED by scripts/build-webapp-vendor.mjs - do not edit.
// es-module-lexer ${lexerPkg.version} (minimal asm.js build), MIT License, Copyright (C) 2018-2022 Guy Bedford.
// Used by the webapp sandbox shim to rewrite ES module specifiers (never regexes).
`;
const out = path.join(repoRoot, "js", "webapp", "lexer-source.js");
fs.writeFileSync(out, `${banner}export const LEXER_VERSION = ${JSON.stringify(lexerPkg.version)};\nexport const LEXER_SOURCE = ${JSON.stringify(code)};\n`);
console.log("wrote", out, `${(code.length / 1024).toFixed(1)} KB`);
